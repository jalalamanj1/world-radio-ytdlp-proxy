#!/usr/bin/env bash
# Install (or update) the complete World Radio proxy stack on an always-on
# Ubuntu VM. Target: Oracle Cloud Always Free (Ampere ARM, Ubuntu 24.04).
#
# Installs and wires up:
#   wr-pot.service      bgutil PO-token provider   (127.0.0.1:4416)
#   wr-proxy.service    the yt-dlp proxy           (:8080)
#   wr-refresh.timer    cookie refresh every 6h, from a persistent Chromium profile
#   wr-load.service     small CPU load so Oracle never marks the VM idle and reclaims it
#
# Safe to re-run: it pulls the latest code and restarts the services.
#
# Secrets live in /etc/wr/wr.env (created on first run, mode 600, root only):
#   ADMIN_TOKEN     generated automatically
#   YT_EMAIL        throwaway YouTube account (used only if the session drops)
#   YT_PASSWORD     ...its password
set -euo pipefail

WR=/opt/wr
REPO=https://github.com/jalalamanj1/world-radio-ytdlp-proxy.git
BGUTIL=https://github.com/Brainicism/bgutil-ytdlp-pot-provider.git
NODE_BIN=/usr/bin/node
log() { printf '\n=== %s ===\n' "$*"; }

log "system packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq --no-install-recommends \
  ca-certificates curl git ffmpeg python3 python3-venv python3-pip openssl

log "node 22 (yt-dlp needs a JS runtime; the PO-token provider needs >= 22)"
if ! command -v node >/dev/null 2>&1 || [ "$(node -v | cut -c2-3)" -lt 22 ]; then
  curl -fsSL https://deb.nodesource.com/setup_22.x | bash -
  apt-get install -y -qq nodejs
fi
node -v

log "service user"
id -u wr >/dev/null 2>&1 || useradd --system --create-home --home-dir "$WR" --shell /usr/sbin/nologin wr

log "python: yt-dlp + PO-token provider plugin"
python3 -m venv "$WR/venv"
"$WR/venv/bin/pip" install -q -U pip
"$WR/venv/bin/pip" install -q -U "yt-dlp[default,curl-cffi]" bgutil-ytdlp-pot-provider
"$WR/venv/bin/yt-dlp" --version

log "PO-token provider (node server)"
if [ -d "$WR/bgutil/.git" ]; then
  git -C "$WR/bgutil" pull -q --ff-only
else
  git clone -q --depth 1 "$BGUTIL" "$WR/bgutil"
fi
( cd "$WR/bgutil/server" && npm install --silent && { npm run --silent build || npx --yes tsc; } )
test -f "$WR/bgutil/server/build/main.js"

log "proxy source"
if [ -d "$WR/app/.git" ]; then
  git -C "$WR/app" pull -q --ff-only
else
  git clone -q --depth 1 "$REPO" "$WR/app"
fi

log "chromium for the cookie refresher"
mkdir -p "$WR/browser"
( cd "$WR/browser" && npm install --silent playwright && npx --yes playwright install --with-deps chromium )
install -m 0644 "$WR/app/deploy/oracle/refresh-cookies.mjs" "$WR/browser/refresh-cookies.mjs"

log "secrets"
mkdir -p /etc/wr
if [ ! -f /etc/wr/wr.env ]; then
  ( umask 077; cat > /etc/wr/wr.env <<EOF
# Generated by setup.sh. Keep this file root-only.
ADMIN_TOKEN=$(openssl rand -hex 32)
# Throwaway YouTube account - only used to re-establish the browser session.
YT_EMAIL=
YT_PASSWORD=
EOF
  )
fi
chmod 600 /etc/wr/wr.env
chown root:root /etc/wr/wr.env

if command -v systemctl >/dev/null 2>&1 && [ -d /run/systemd/system ]; then
  log "systemd units"
  cat > /etc/systemd/system/wr-pot.service <<'EOF'
[Unit]
Description=bgutil PO-token provider for yt-dlp
After=network-online.target
Wants=network-online.target

[Service]
User=wr
WorkingDirectory=/opt/wr/bgutil/server
ExecStart=/usr/bin/node /opt/wr/bgutil/server/build/main.js --host 127.0.0.1 --port 4416
Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF

  cat > /etc/systemd/system/wr-proxy.service <<'EOF'
[Unit]
Description=World Radio yt-dlp proxy
After=network-online.target wr-pot.service
Wants=network-online.target
Requires=wr-pot.service

[Service]
User=wr
WorkingDirectory=/opt/wr/app
EnvironmentFile=/etc/wr/wr.env
Environment=PORT=8080
Environment=HOST=127.0.0.1
Environment=YTDLP_PATH=/opt/wr/venv/bin/yt-dlp
Environment=YTDLP_JS_RUNTIME=node
Environment=YTDLP_COOKIES=/opt/wr/cookies.txt
Environment=PREFETCH=1
Environment=RESOLVE_TTL_MS=3600000
Environment=SEARCH_TTL_MS=600000
ExecStart=/usr/bin/node /opt/wr/app/server.mjs
Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF

  cat > /etc/systemd/system/wr-refresh.service <<'EOF'
[Unit]
Description=Refresh YouTube cookies for the World Radio proxy
After=network-online.target wr-proxy.service
Wants=network-online.target
Requires=wr-proxy.service

[Service]
Type=oneshot
User=wr
WorkingDirectory=/opt/wr/browser
EnvironmentFile=/etc/wr/wr.env
Environment=WR_PROFILE=/opt/wr/profile
Environment=WR_COOKIE_DEST=/opt/wr/cookies.txt
ExecStart=/usr/bin/node /opt/wr/browser/refresh-cookies.mjs
EOF

  cat > /etc/systemd/system/wr-refresh.timer <<'EOF'
[Unit]
Description=Refresh YouTube cookies every 6 hours

[Timer]
OnBootSec=2min
OnUnitActiveSec=6h
Persistent=true

[Install]
WantedBy=timers.target
EOF

  # Oracle reclaims Always Free instances whose 95th-percentile CPU stays under
  # ~10%, which is exactly what an idle proxy looks like. Half a core of busy
  # work keeps it comfortably above that. Disable with: systemctl disable --now wr-load
  cat > /etc/systemd/system/wr-load.service <<'EOF'
[Unit]
Description=Small CPU load so Oracle never reclaims this Always Free VM as idle

[Service]
ExecStart=/bin/sh -c 'while :; do :; done'
CPUQuota=50%
Restart=always

[Install]
WantedBy=multi-user.target
EOF

  chown -R wr:wr "$WR"
  # The proxy writes a copy of the jar next to it, so the profile dir must be writable.
  systemctl daemon-reload
  systemctl enable --now wr-pot.service wr-proxy.service wr-refresh.timer wr-load.service
  systemctl --no-pager --lines=0 status wr-pot wr-proxy wr-load || true
else
  log "no systemd here - skipping service install (expected inside a container)"
fi

log "done"
echo "proxy      : http://127.0.0.1:8080/health"
echo "secrets    : /etc/wr/wr.env"
echo "cookies    : /opt/wr/cookies.txt"
echo "next       : seed cookies once, then 'systemctl start wr-refresh.service'"
